// Parse one level definition into runtime data. Loot value: ordinary 100, the
// final level's last piece is the Clockwork Orchid, worth 500.
export function parseLevel(def, index) {
  const grid = def.grid.map((row) => row.split(''));
  const spawn = { x: 0, y: 0 };
  const exit = { x: 0, y: 0 };
  const loot = [];
  let spawnCount = 0;
  let exitCount = 0;
  for (let y = 0; y < grid.length; y++) {
    for (let x = 0; x < grid[y].length; x++) {
      const c = grid[y][x];
      if (c === 'P') { spawn.x = x; spawn.y = y; spawnCount++; grid[y][x] = '.'; }
      if (c === 'E') { exit.x = x; exit.y = y; exitCount++; grid[y][x] = '.'; }
      if (c === 'L') {
        loot.push({ tx: x, ty: y, value: 100, taken: false });
        grid[y][x] = '.';
      }
    }
  }
  if (index === LEVELS.length - 1 && loot.length) loot[loot.length - 1].value = 500;
  return {
    index, name: def.name, sub: def.sub, par: def.par, grid,
    spawn, exit, loot,
    guards: def.guards, cameras: def.cameras, lasers: def.lasers, tripwires: def.tripwires,
    spawnCount, exitCount,
  };
}

export function tileCenter(tx, ty) {
  return { x: tx * TILE + TILE / 2, y: ty * TILE + TILE / 2 };
}
